import {test,expect,type APIRequestContext} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {readFileSync,mkdirSync,writeFileSync} from 'node:fs';
import {randomUUID} from 'node:crypto';
const access=JSON.parse(readFileSync('.private/local-runtime/access.json','utf8')) as {first:string;second:string};
test('real HTTP customer journey with local PostgreSQL and live public GitHub/OSV',async({page,browser})=>{
  const evidence:string[]=[];
  const health=await (await page.request.get('/api/health')).json();expect(health.publicDemo).toBe(false);
  await page.goto('/sign-in');
  await page.getByLabel('Individual access key').fill(access.first);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page).toHaveURL(/\/reports/);await expect(page.getByText('Sign in to save scans. Demos show dated evidence.',{exact:true})).toHaveCount(0);evidence.push('Actual local operator-key sign-in; not GitHub OAuth');
  const initial=await (await page.request.get('/api/usage')).json();
  const repository='chilu18/shiptested-fresh-judge-demo';
  await page.goto('/scan');await page.getByLabel('GitHub repository URL').fill(`https://github.com/${repository}`);
  await page.getByRole('button',{name:'Scan repository',exact:true}).click();
  await expect(page).toHaveURL(/job=[a-f0-9-]{36}/);
  const jobId=new URL(page.url()).searchParams.get('job')!;
  await page.reload();
  await expect(page.getByRole('link',{name:'Open private report'})).toBeVisible({timeout:150000});
  await page.getByRole('link',{name:'Open private report'}).click();
  await expect(page).toHaveURL(/\/reports\/[a-f0-9-]{36}$/);
  const reportId=new URL(page.url()).pathname.split('/')[2];
  const response=await page.request.get(`/api/scans/${reportId}`);expect(response.status()).toBe(200);
  const {report}=await response.json();
  expect(report.repositoryScan.repository).toBe(repository);expect(report.repositoryScan.commit).toMatch(/^[a-f0-9]{40}$/);
  expect(report.repositoryScan.manifests).toContain('package-lock.json');expect(report.findings.length).toBeGreaterThan(0);
  await expect(page.getByRole('region',{name:'Repository provenance'})).toContainText(report.repositoryScan.commit.slice(0,7));
  await page.reload();await expect(page.getByRole('heading',{name:'Scan report',exact:true})).toBeVisible();
  evidence.push('Real queue, sequential worker, live GitHub/OSV lookup, PostgreSQL report persistence and browser reload');
  const privateContext=await browser.newContext({baseURL:'http://127.0.0.1:3157'});
  const second=await privateContext.request.post('/api/session',{data:{key:access.second}});expect(second.status()).toBe(200);
  expect((await privateContext.request.get(`/api/scans/${reportId}`)).status()).toBe(404);
  expect((await privateContext.request.get(`/api/repository-scans/${jobId}`)).status()).toBe(404);
  expect((await privateContext.request.get(`/api/scans/${reportId}/comparison`)).status()).toBe(404);
  await privateContext.close();evidence.push('Independent local account denied report, job and comparison');
  const key=randomUUID(),input={repository,privateAccess:false,requestKey:key};
  const queued=await page.request.post('/api/repository-scans',{data:input});expect(queued.status()).toBe(202);
  const next=await queued.json();
  const duplicate=await page.request.post('/api/repository-scans',{data:input});expect(duplicate.status()).toBe(202);expect((await duplicate.json()).id).toBe(next.id);
  const wait=async(request:APIRequestContext,id:string)=>{
    let job:{state:string;reportUrl?:string};
    await expect.poll(async()=>{job=await (await request.get(`/api/repository-scans/${id}`)).json();return job.state;},{timeout:150000,intervals:[1000,2000]}).toBe('completed');
    return job!;
  };
  const finished=await wait(page.request,next.id);
  const after=await (await page.request.get('/api/usage')).json();expect(after.reserved-initial.reserved).toBe(2);
  await page.goto(finished.reportUrl!);
  await expect(page.getByRole('region',{name:'Scan comparison'})).toContainText('unchanged');
  evidence.push('Repeat scan comparison and idempotent submission: exactly two reservations for two scans');
  for(const width of [1440,390])for(const theme of ['dark','light']){
    await page.setViewportSize({width,height:960});await page.evaluate(value=>{document.documentElement.dataset.theme=value;localStorage.setItem('shipcheck-theme',value);},theme);
    await page.evaluate(async()=>{await document.fonts.ready;await Promise.all(document.getAnimations().filter(a=>a.effect?.getTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{})));});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    const axe=await new AxeBuilder({page}).analyze();expect(axe.violations.filter(v=>['serious','critical'].includes(v.impact||''))).toEqual([]);
    await page.screenshot({path:`test-results/journey/report-${width}-${theme}.png`,fullPage:true});
  }
  await page.goto(`/reports/${reportId}/findings/${encodeURIComponent(report.findings[0].id)}`);
  await expect(page.getByRole('heading',{name:'Recommended action',exact:true})).toBeVisible();
  await page.getByRole('link',{name:'Prepare tested repair'}).click();
  await expect(page).toHaveURL(new RegExp(`report=${reportId}`));
  await expect(page.getByRole('link',{name:'Connect GitHub repositories'})).toBeVisible();
  evidence.push('Finding-to-repair handoff preserves report and repository; missing provider grants lead to connection guidance');
  await page.request.delete('/api/session');expect((await page.request.get(`/api/scans/${reportId}`)).status()).toBe(401);
  await page.goto(`/reports/${reportId}`);await expect(page.getByText('Report unavailable',{exact:true})).toBeVisible();
  expect((await page.request.post('/api/session',{data:{key:access.first}})).status()).toBe(200);
  await page.goto(`/reports/${reportId}`);await expect(page.getByRole('heading',{name:'Scan report',exact:true})).toBeVisible();
  evidence.push('Sign-out denies exact private URL; fresh sign-in restores the same saved report');
  mkdirSync('test-results/journey',{recursive:true});
  writeFileSync('test-results/journey/customer.json',JSON.stringify({verifiedAt:new Date().toISOString(),repository,commit:report.repositoryScan.commit,reportId,jobId,checks:evidence,notVerified:['GitHub OAuth/App customer onboarding','Paid sandbox execution','Actual GitHub draft PR publication','Hosted deployment','Stripe lifecycle']},null,2));
});
